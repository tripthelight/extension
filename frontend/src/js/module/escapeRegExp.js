/**
 * 문자열 안의 정규식 특수문자를 이스케이프합니다.
 *
 * 예:
 * - "."   -> "\\."
 * - "*"   -> "\\*"
 * - "[a]" -> "\\[a\\]"
 *
 * 주로 사용자 입력 문자열을 RegExp 생성자에
 * 그대로 넣어야 할 때 사용합니다.
 *
 * @param {string} str
 * 이스케이프할 원본 문자열
 *
 * @returns {string}
 * 정규식 특수문자가 역슬래시로 이스케이프된 문자열
 */
export default (str) => {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}